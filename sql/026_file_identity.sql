create or replace function file_identity_fold_v1(value text)
returns text language sql stable strict as $$
  select coalesce(string_agg(coalesce(mapping.folded,part.character),'' order by part.position),'')
  from regexp_split_to_table(value,'') with ordinality part(character,position)
  left join file_identity_casefold_v1 mapping on mapping.source=part.character collate "C"
$$;

-- Full folding is opt-in for explicit native case-insensitive root rules.
create or replace function file_identity_comparison(value text, version text)
returns text language sql stable strict as $$
  select case version when 'nfc-sensitive-v1' then normalize(value,NFC)
    when 'nfc-fold-v1' then normalize(file_identity_fold_v1(normalize(value,NFC)),NFC) end
$$;

create or replace function file_identity_root(owner uuid)
returns uuid language plpgsql as $$
declare root_id uuid;
begin
  insert into file_identity_roots(owner_id) values(owner) on conflict(owner_id) do nothing;
  select id into strict root_id from file_identity_roots where owner_id=owner;
  return root_id;
end $$;

create or replace function file_identity_node_write()
returns trigger language plpgsql as $$
declare root_id uuid; expected_parent uuid; version text; folder boolean;
  parent_path text; segment text; ancestor text := ''; ancestor_parent text := '';
begin
  if TG_OP='UPDATE' then
    if NEW.id is distinct from OLD.id then
      raise exception 'file identity cannot change on update' using errcode='23514';
    end if;
    if OLD.owner_id is not null and NEW.owner_id is distinct from OLD.owner_id then
      raise exception 'file identity owner cannot change on update' using errcode='23514';
    end if;
  end if;
  -- Unclaimed legacy rows acquire identity when an owner claims them.
  if NEW.owner_id is null then
    NEW.parent_id := null;
    NEW.comparison_name := normalize(NEW.name,NFC);
    return NEW;
  end if;
  if NEW.path='' or NEW.path ~ '(^/|/$|//|(^|/)\.\.?(/|$))' then
    raise exception 'file identity requires a non-root relative logical path' using errcode='23514';
  end if;
  parent_path := regexp_replace(NEW.path,'(^|/)[^/]+$','');
  if NEW.parent<>parent_path or NEW.name<>regexp_replace(NEW.path,'^.*/','') then
    raise exception 'file identity path, parent and name disagree' using errcode='23514';
  end if;
  root_id := file_identity_root(NEW.owner_id);
  select name_comparison_version into strict version from file_identity_roots where owner_id=NEW.owner_id for share;
  expected_parent := root_id;
  -- Only literal, known logical ancestors are synthesized. Keys retain the
  -- existing private index namespace, not a new authoritative storage layout.
  if parent_path<>'' then
    foreach segment in array string_to_array(parent_path,'/') loop
      ancestor := case when ancestor='' then segment else ancestor||'/'||segment end;
      select id,is_dir into expected_parent,folder from nodes
        where owner_id=NEW.owner_id and path=ancestor;
      if not found then
        insert into nodes(owner_id,key,path,parent,name,is_dir)
          values(NEW.owner_id,'drive/'||NEW.owner_id::text||'/'||ancestor||'/',ancestor,ancestor_parent,segment,true)
          on conflict(owner_id,path) do nothing;
        select id,is_dir into strict expected_parent,folder from nodes
          where owner_id=NEW.owner_id and path=ancestor;
      end if;
      if not folder then
        raise exception 'file identity parent is not a folder' using errcode='23514';
      end if;
      ancestor_parent := ancestor;
    end loop;
  end if;
  if TG_OP='INSERT' then
    if NEW.parent_id is not null and NEW.parent_id<>expected_parent then
      raise exception 'file identity parent belongs to another owner or path' using errcode='23514';
    end if;
  elsif NEW.parent_id is distinct from OLD.parent_id and NEW.parent_id is distinct from expected_parent then
    raise exception 'file identity parent belongs to another owner or path' using errcode='23514';
  end if;
  NEW.parent_id := expected_parent;
  NEW.comparison_name := file_identity_comparison(NEW.name,version);
  return NEW;
end $$;

do $$
begin
  if not exists(select 1 from pg_trigger where tgrelid='nodes'::regclass and tgname='file_canonical_node_write') then
    drop trigger if exists file_identity_node_write on nodes;
    create trigger file_identity_node_write before insert or update on nodes
      for each row execute function file_identity_node_write();
  end if;
end $$;

-- Seed existing accounts, including empty accounts, without synthetic nodes.
insert into file_identity_roots(owner_id) select id from users on conflict(owner_id) do nothing;
-- Parent-before-child repair also handles imports which omitted folder markers.
do $$
declare item record;
begin
  if exists(select 1 from pg_trigger where tgrelid='nodes'::regclass and tgname='file_canonical_node_write') then
    return;
  end if;
  for item in select id from nodes order by length(path),path loop
    update nodes set comparison_name=comparison_name where id=item.id;
  end loop;
end $$;

-- Existing ambiguous spellings fail explicitly; no path is silently renamed.
create unique index if not exists nodes_owner_parent_comparison_uniq
  on nodes(owner_id,parent_id,comparison_name);

create or replace function file_identity_root_write()
returns trigger language plpgsql as $$
begin
  if NEW.id is distinct from OLD.id or NEW.owner_id is distinct from OLD.owner_id then
    raise exception 'root identity cannot change on update' using errcode='23514';
  end if;
  return NEW;
end $$;
drop trigger if exists file_identity_root_write on file_identity_roots;
create trigger file_identity_root_write before update on file_identity_roots
  for each row execute function file_identity_root_write();

create or replace function file_identity_root_rules_changed()
returns trigger language plpgsql as $$
begin
  if NEW.name_comparison_version is distinct from OLD.name_comparison_version then
    update nodes set comparison_name=file_identity_comparison(name,NEW.name_comparison_version)
      where owner_id=NEW.owner_id;
  end if;
  return NEW;
end $$;
drop trigger if exists file_identity_root_rules_changed on file_identity_roots;
create trigger file_identity_root_rules_changed after update on file_identity_roots
  for each row execute function file_identity_root_rules_changed();
